# ============================================================
# <PROJECT NAME>  |  Local dev bundle builder
# ------------------------------------------------------------
# NOT the MakerWorld bundle (that is build.ps1). Produces
# dist/<PROJECT_SLUG>_dev.scad: the whole project as one file you can open
# in the OpenSCAD desktop app without juggling include/use paths, with:
#   - every comment and every color() kept (it is for you, not PMM)
#   - a "Dev view" customizer dropdown choosing which module to render,
#     generated from DEV_VIEWS in scripts/project_config.sh
#   - dev-only $fa/$fs sliders for a fast, coarse preview
#   - "MakerWorld assembly plate" (mw_assembly_view) always selectable when
#     ASSEMBLY_PLATE_VIEWS is set, plus a dev_view_offset XY shift -- the 3mf
#     export renders its assembly preview plate from this bundle with both
#   - a dev_assembly_regions list, looped as $assembly_region at the TOP
#     level, so the 3mf export can render the preview plate one color region
#     per solid (docs/workflows/multicolor.md, "The assembly preview plate")
#
# Gitignored (dist/*_dev.scad) -- a throwaway convenience, regenerate any
# time. Runs the same plate validation as build.ps1, so it fails the same
# way on drift.
#
# Usage:
#   scripts\dev_build.bat
#   powershell -File scripts/build/dev_build.ps1 [-Project examples/demo]
# See: docs/toolchain/pipelines.md ("Dev bundle")
# ============================================================
param([string]$Project = "")

$ErrorActionPreference = "Stop"
Import-Module (Join-Path $PSScriptRoot "Bundle.psm1") -Force

$ctx = Get-ProjectContext -Project $Project
$plates = Update-PlatesJson -Ctx $ctx
Assert-PlateModulesMatch -Ctx $ctx -Plates $plates
Assert-AssemblyViewsExist -Ctx $ctx -Plates $plates
$injected = @(Get-BundleInjectedLines -Ctx $ctx -Plates $plates)

# DEV_VIEWS entries are "module_name:Label" -- see project_config.sh.
$views = @()
foreach ($entry in $ctx.DevViews) {
    $pair = $entry.Split(":", 2)
    $label = $pair[0]
    if ($pair.Count -gt 1) { $label = $pair[1] }
    $views += [pscustomobject]@{ Module = $pair[0]; Label = $label }
}
if ($views.Count -eq 0) { throw "DEV_VIEWS is empty in scripts/project_config.sh -- nothing to preview." }

# The MakerWorld assembly plate is always selectable when assembly views are
# configured: scripts/export/export_3mf.sh renders its preview plate from this
# bundle with -D dev_view="mw_assembly_view" (a flat bundle, so parameter
# overrides reach every part regardless of include/use scoping).
$hasAssemblyViews = @(Get-AssemblyViews -Plates $plates).Count -gt 0
if ($hasAssemblyViews -and -not ($views | Where-Object { $_.Module -eq "mw_assembly_view" })) {
    $views += [pscustomobject]@{ Module = "mw_assembly_view"; Label = "MakerWorld assembly plate" }
}

$b = New-Object System.Collections.Generic.List[string]
$b.Add("// ============================================================")
$b.Add("// $($ctx.Name)  |  LOCAL DEV BUNDLE -- not for MakerWorld")
$b.Add("// GENERATED by scripts/build/dev_build.ps1 -- do not edit by hand.")
$b.Add("// Pick what to render in the Customizer panel (Window > Customizer).")
$b.Add("// ============================================================")
$b.Add("")
$b.Add("/* [Dev view] */")
$b.Add("")
$b.Add("// Which module to render")
$options = ($views | ForEach-Object { "$($_.Module):$($_.Label)" }) -join ", "
$b.Add("dev_view = `"$($views[0].Module)`"; // [$options]")
$b.Add("")
$b.Add("// XY shift applied to the rendered view. The 3mf export sets it (-D) to the")
$b.Add("// bed center for its assembly preview plate; leave at [0, 0] otherwise.")
$b.Add("dev_view_offset = [0, 0];")
$b.Add("")
$b.Add("// assembly_region() names to render one per top-level solid. The 3mf export")
$b.Add("// sets it (-D) for a multicolor preview plate; leave at [] otherwise.")
$b.Add("dev_assembly_regions = [];")
$b.Add("")
$b.Add("// Preview curve smoothness in degrees (lower = finer, slower)")
$b.Add("dev_render_fa = 12; // [1:1:60]")
$b.Add("")
$b.Add("// Preview minimum fragment size in mm (lower = finer, slower)")
$b.Add("dev_render_fs = 2; // [0.1:0.1:5]")
$b.Add("")

foreach ($file in $ctx.SourceFiles) {
    $path = Join-Path $ctx.Dir $file
    if (-not (Test-Path $path)) { throw "Source file not found (SOURCE_FILES): $file" }
    $isParams = ($file -eq $ctx.ParamsFile)
    $b.Add("// ---- from $file ----")
    $selected = Select-BundleLines -Lines @(Get-Content -Path $path -Encoding UTF8) -IsParams $isParams -Mode "dev" -Ctx $ctx
    $rest = @()
    if ($isParams) { $rest = Set-InjectedValues -Lines $selected -Injected $injected }
    foreach ($l in $selected) { $b.Add($l) }
    foreach ($l in $rest) { $b.Add($l) }
    $b.Add("")
}

$b.Add("// ---- dev preview -------------------------------------------------")
$b.Add('$fa = dev_render_fa;')
$b.Add('$fs = dev_render_fs;')
$b.Add("")
$b.Add("// A TOP-LEVEL for: with --enable=lazy-union each iteration stays its own")
$b.Add("// solid (lazy-union does not reach inside a module call). [undef] = one")
$b.Add("// pass with no region filter, i.e. everything.")
$b.Add("for (`$assembly_region = len(dev_assembly_regions) > 0 ? dev_assembly_regions : [undef])")
$b.Add("translate([dev_view_offset[0], dev_view_offset[1], 0]) {")
for ($i = 0; $i -lt $views.Count; $i++) {
    $keyword = "    } else if"
    if ($i -eq 0) { $keyword = "    if" }
    $b.Add("$keyword (dev_view == `"$($views[$i].Module)`") {")
    $b.Add("        $($views[$i].Module)();")
}
$b.Add("    }")
$b.Add("}")

Write-Utf8NoBom -Path $ctx.DevOut -Lines $b
Write-Host "Dev bundle written: $($ctx.DevOut)  (pick a view via the dev_view dropdown)"
